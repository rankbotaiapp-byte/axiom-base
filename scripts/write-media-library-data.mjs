import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "public", "media");
const SKIP = /\.(zip|webmanifest|json)$/i;
const SKIP_DIR = /^(characters)$/i;
const IMAGE = /\.(png|jpe?g|webp|gif|svg)$/i;
const VIDEO = /\.(mp4|webm)$/i;

function toPosix(p) {
  return p.split(sep).join("/");
}

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) {
      if (SKIP_DIR.test(name)) continue;
      walk(full, acc);
      continue;
    }
    if (SKIP.test(name) || (!IMAGE.test(name) && !VIDEO.test(name))) continue;
    if (st.size < 400) continue;
    const rel = `/media/${toPosix(relative(root, full))}`;
    acc.push({ rel, name });
  }
  return acc;
}

function classify(rel) {
  const h = rel.toLowerCase();
  let theme = "cinematic";
  if (/plumb|locksmith|electric|emergency|911|hvac/.test(h)) theme = "emergency";
  else if (/land-clear|protection|gunsmith|tactic|cyber-sting|drone|chainsaw|hidden-gun/.test(h)) theme = "tactical";
  else if (/cyber|orb|obsidian|aether|holo|galax|design|graphic|augment|ai-female|ai-male/.test(h)) theme = "tech-cyber";
  else if (/leopard|leapard|otter|owl|bear|shark|tiger|trout|fox|eagle|taxidermy|raptor|fish|hawk|wildlife/.test(h))
    theme = "wildlife";
  else if (/auto|car-|burnout|garage|moto|bike|helmet|apex|gt3|truck|van|mechanic|racing|dirtbike|streetbike|tune/.test(h))
    theme = "auto";
  else if (/wood|firewood|weld|landscape|horticult|paint|clean|barber|roof|contractor|hvac|store-front|salon|beauty|asthetic/.test(h))
    theme = "trades";
  const niches = [];
  const add = (n) => {
    if (!niches.includes(n)) niches.push(n);
  };
  if (/plumb/.test(h)) add("plumbing");
  if (/electric/.test(h)) add("electrical");
  if (/hvac/.test(h)) add("hvac");
  if (/lock/.test(h)) add("security");
  if (/barber/.test(h)) add("barber");
  if (/beauty|salon|asthetic/.test(h)) add("beauty-salon");
  if (/auto|car|garage|mechanic|tune|burnout/.test(h)) add("auto");
  if (/moto|bike|helmet|apex|gt3|power/.test(h)) add("power-sports");
  if (/land-clear|forest|wood|chainsaw|firewood/.test(h)) add("forestry");
  if (/landscape|horticult/.test(h)) add("landscaping");
  if (/taxidermy|leopard|owl|bear|tiger|wildlife/.test(h)) add("taxidermy");
  if (/fish|trout|hawk|guide/.test(h)) add("taxidermy");
  if (/train|fitness/.test(h)) add("personal-trainer");
  if (/roof/.test(h)) add("roofing");
  if (/clean/.test(h)) add("contractor");
  if (/gun|protect/.test(h)) add("security");
  if (/bow/.test(h)) add("bow-tech");
  if (/weld|fabric/.test(h)) add("fabrication");
  if (/machine/.test(h)) add("machining");
  if (/dog|pet|canine/.test(h)) add("canine");
  if (/drone/.test(h)) add("contractor");
  if (!niches.length) add("contractor");
  return { theme, niches };
}

function label(rel) {
  const raw = rel
    .replace(/^\/media\//, "")
    .replace(/^.*\//, "")
    .replace(/(\.mp4)+$/i, "")
    .replace(/\.(png|jpe?g|webp|gif|svg|webm)$/i, "");
  const words = raw
    .split(/[-_.]+/)
    .filter((w) => w && !["mp4", "png", "jpg", "jpeg", "hero", "animation", "loop"].includes(w.toLowerCase()))
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
  return words.join(" ") || "Media";
}

const files = walk(root).sort((a, b) => a.rel.localeCompare(b.rel));
const stems = new Map();
for (const f of files) {
  const stem = f.rel.replace(/(\.mp4)+$/i, "").replace(/\.(png|jpe?g|webp|gif|svg|webm)$/i, "");
  if (!stems.has(stem)) stems.set(stem, []);
  stems.get(stem).push(f);
}

const seen = new Set();
const rows = [];
for (const f of files) {
  if (/\.mp4\.mp4$/i.test(f.rel)) {
    const clean = f.rel.replace(/\.mp4$/i, "");
    if (files.some((x) => x.rel === clean)) continue;
  }
  if (seen.has(f.rel)) continue;
  seen.add(f.rel);
  const kind = /\.mp4$/i.test(f.rel) ? "loop" : IMAGE.test(f.rel) ? "still" : "loop";
  const { theme, niches } = classify(f.rel);
  const stem = f.rel.replace(/(\.mp4)+$/i, "").replace(/\.(png|jpe?g|webp|gif|svg|webm)$/i, "");
  const sibs = stems.get(stem) || [];
  const thumb = sibs.find((s) => IMAGE.test(s.rel) && s.rel !== f.rel)?.rel || f.rel;
  const id = f.rel
    .replace(/^\/media\//, "")
    .replace(/[^a-z0-9]+/gi, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
  rows.push({ id, url: f.rel, kind: kind === "loop" && /\.webm$/i.test(f.rel) ? "loop" : kind, theme, niches, label: label(f.rel), thumbnail: thumb });
}

const json = JSON.stringify(rows, null, 2);
writeFileSync(new URL("../src/config/mediaLibrary.data.ts", import.meta.url), `/** Auto-indexed from public/media. Regenerated by scripts/write-media-library-data.mjs */

export const MEDIA_LIBRARY_RECORDS = ${json} as const;
`);
console.log("wrote", rows.length, "posix urls", rows.filter((r) => r.url.includes("\\")).length);
